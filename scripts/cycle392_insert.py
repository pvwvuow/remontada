#!/usr/bin/env python3
# cycle-392 — insert the generated map block into src/lib/player-names-fa.ts
# just before the closing brace of PLAYER_NAME_FA, with the provenance header.
import io, sys, re

PATH = "src/lib/player-names-fa.ts"
BLOCK = open("scripts/cycle392-map-block.txt", encoding="utf-8").read().rstrip("\n")

src = io.open(PATH, encoding="utf-8").read()
import re as _re
new_block_full = BLOCK
# regenerate-friendly: replace an existing cycle-392 block in place
if 'cycle-392: the transfers-surface pool' in src:
    pattern = _re.compile(
        r'  // — cycle-392: the transfers-surface pool.*?\n(  "[^"]+": "[^"]+",\n)+',
        _re.S,
    )
    if not pattern.search(src):
        print("HARD FAIL — cycle-392 header found but block not matched", file=sys.stderr)
        sys.exit(1)
    replacement = (
        "  // — cycle-392: the transfers-surface pool (byte-exact harvest\n"
        "  // scripts/cycle392-transfers-raw.json: 465 unique raw names across\n"
        "  // league-transfers {pl,laliga,seriea,bundesliga,ligue1} + the\n"
        "  // team-transfers flagship trio, 601 items). Entries generated by\n"
        "  // scripts/cycle392_gen_map.py — keys resolved against the harvest\n"
        "  // JSON (no guessed spellings, hard-fail on a miss). The remaining\n"
        "  // raw names keep the honest Latin passthrough per the cycle-96/104\n"
        "  // convention (ambiguous/less-known transliterations stay absent).\n"
        + BLOCK + "\n"
    )
    src = pattern.sub(lambda m: replacement, src, count=1)
    io.open(PATH, "w", encoding="utf-8").write(src)
    n = len(re.findall(r'"', BLOCK)) // 2
    print(f"regenerated — block now {n} entries")
    sys.exit(0)

anchor = '  "malick thiaw": "مالیک تیاو",\n};'
if anchor not in src:
    print("HARD FAIL — anchor not found", file=sys.stderr)
    sys.exit(1)

header = (
    '  "malick thiaw": "مالیک تیاو",\n'
    "  // — cycle-392: the transfers-surface pool (byte-exact harvest\n"
    "  // scripts/cycle392-transfers-raw.json: 465 unique raw names across\n"
    "  // league-transfers {pl,laliga,seriea,bundesliga,ligue1} + the\n"
    "  // team-transfers flagship trio, 601 items). Entries generated by\n"
    "  // scripts/cycle392_gen_map.py — keys resolved against the harvest\n"
    "  // JSON (no guessed spellings, hard-fail on a miss). The remaining\n"
    "  // raw names keep the honest Latin passthrough per the cycle-96/104\n"
    "  // convention (ambiguous/less-known transliterations stay absent).\n"
    + BLOCK + "\n};"
)
new = src.replace(anchor, header, 1)
io.open(PATH, "w", encoding="utf-8").write(new)
n = len(re.findall(r'"', BLOCK)) // 2
print(f"inserted — {n} entries appended")
