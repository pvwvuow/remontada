#!/usr/bin/env python3
# cycle-395 — insert the generated squad-surface map block into
# src/lib/player-names-fa.ts just before the closing brace of
# PLAYER_NAME_FA, with the provenance header (the 392 pattern).
import io, re, sys

PATH = "src/lib/player-names-fa.ts"
BLOCK = open("scripts/cycle395-map-block.txt", encoding="utf-8").read().rstrip("\n")

src = io.open(PATH, encoding="utf-8").read()

# regenerate-friendly: replace an existing cycle-395 block in place
if "cycle-395: the squad-surface pool" in src:
    pattern = re.compile(
        r'  // — cycle-395: the squad-surface pool.*?\n(  "[^"]+": "[^"]+",\n)+',
        re.S,
    )
    if not pattern.search(src):
        print("HARD FAIL — cycle-395 header found but block not matched", file=sys.stderr)
        sys.exit(1)
    replacement = (
        "  // — cycle-395: the squad-surface pool (byte-exact harvest\n"
        "  // scripts/cycle395-squads-raw.json: 120 unique raw names across\n"
        "  // 218 squad rows on the seven flagship teams — liverpool 8650,\n"
        "  // newcastle 10261, persepolis 101610, hull 8667, omonia 8044,\n"
        "  // iran-nt 6711, argentina-nt 6706). Entries generated by\n"
        "  // scripts/cycle395_gen_map.py — keys resolved against the harvest\n"
        "  // JSON (no guessed spellings, hard-fail on a miss) and de-duped\n"
        "  // against the pre-existing map. The remaining raw names keep the\n"
        "  // honest Latin passthrough per the cycle-96/104 convention\n"
        "  // (ambiguous/less-known transliterations stay absent).\n"
        + BLOCK + "\n"
    )
    src = pattern.sub(lambda m: replacement, src, count=1)
    io.open(PATH, "w", encoding="utf-8").write(src)
    n = len(re.findall(r'"', BLOCK)) // 2
    print(f"regenerated — block now {n} entries")
    sys.exit(0)

anchor = '  "xavi grande": "خاوی گرنده",\n};'
if src.count(anchor) != 1:
    print("HARD FAIL — anchor not found exactly once", file=sys.stderr)
    sys.exit(1)

header = (
    '  "xavi grande": "خاوی گرنده",\n'
    "  // — cycle-395: the squad-surface pool (byte-exact harvest\n"
    "  // scripts/cycle395-squads-raw.json: 120 unique raw names across\n"
    "  // 218 squad rows on the seven flagship teams — liverpool 8650,\n"
    "  // newcastle 10261, persepolis 101610, hull 8667, omonia 8044,\n"
    "  // iran-nt 6711, argentina-nt 6706). Entries generated by\n"
    "  // scripts/cycle395_gen_map.py — keys resolved against the harvest\n"
    "  // JSON (no guessed spellings, hard-fail on a miss) and de-duped\n"
    "  // against the pre-existing map. The remaining raw names keep the\n"
    "  // honest Latin passthrough per the cycle-96/104 convention\n"
    "  // (ambiguous/less-known transliterations stay absent).\n"
    + BLOCK + "\n};"
)
new = src.replace(anchor, header, 1)
io.open(PATH, "w", encoding="utf-8").write(new)
n = len(re.findall(r'"', BLOCK)) // 2
print(f"inserted — {n} entries appended")
